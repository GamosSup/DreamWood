## Паспорт
- Электротяга на рельсах, **6 машин**
- Скорость 3,6 км/ч (макс. 6 км/ч), время в пути **180 секунд**
- Вместимость: **4 пассажира** (2 спереди, 2 сзади)
- Погода: от **+5°C**, ветер до 15 м/с. Гроза, град, сильный ветер — закрываем

## Допуск
- **Разрешено:** самостоятельная поездка от 125 см; фото/видео в пути
- **Внимание:** дети до 95 см — строго **без VR-шлемов**. Беременных и гостей с особенностями здоровья предупреждаем о рисках до посадки
- **Строго запрещено:** обходить джип снаружи, вставать и отстёгиваться в пути, сажать гостей без диэлектрического коврика, катать нетрезвых
- Если гость забыл про ремень или пытается обойти джип сзади — машина никуда не едет

## VR-шлемы
- Надевание: гость смотрит строго **вперёд по ходу движения**, чтобы реальность совпала с виртуальностью; наушники плотно прижать
- Резкость: колёсико сверху
- Сенсор на правом виске — «затвор фотоаппарата», больше кнопок не нажимать
- Шлем не снимать до полной остановки (иначе укачает)

## Посадка
- Диэлектрический коврик на месте, вещи оставлены на платформе
- Сначала **задний ряд**: ОДНИМ ремнём пристёгиваем двоих (слева направо)
- Правило: 1 взрослый + 1 ребёнок сидят парами
- Потом передний ряд, **водитель садится самым последним**, одним ремнём
- Сажаем только со стороны входа, обходить машину нельзя

## Скрипты
- Встреча: «Бодрого дня, искатели приключений! Готовы покорить сафари?»
- Инструктаж: «Обязательно придерживайтесь инструкций и смотрите в оба! Вы готовы стать фотоохотниками?»
- Высадка: «Теперь вам море по колено! Возвращайтесь к нам за новыми тайнами!»

## Пульт: три кнопки
- **«Посадка»:** отправляет машину в путь (только после скриптов и проверки ремней)
- **«Высадка»:** направляет вернувшуюся машину на станцию посадки
- **Красная:** экстренная остановка

