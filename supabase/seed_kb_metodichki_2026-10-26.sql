## Маршруты
- **Семейный (лёгкий):** 120 м, до 21 гостя. Возраст 4–12 лет только с сопровождением, 12+ без. Рост **100–205 см**
- **Мастер (средний):** 146 м, до 19 гостей. Возраст от 14 лет. Рост **150–205 см**
- **Герой (сложный):** 167 м, до 21 гостя. Возраст от 16 лет. Рост **160–205 см**
- **Максимальный вес для всех маршрутов — 110 кг**

## Нельзя (медицинские ограничения)
- Голова: болезни вестибулярного аппарата, головокружения, боязнь высоты, психические особенности
- Спина и тело: заболевания позвоночника, шеи, опорно-двигательного аппарата, недавние операции
- Сердце: сердечно-сосудистые заболевания, кардиостимулятор
- Общее: опьянение, беременность, неподходящая одежда и обувь, зонты, животные
- Одежда: только закрытая обувь и спортивные штаны

## Роли и запрет
- **Инструктирующий:** подбор маршрута, скрипты, выдача обвязки
- **Страхующий:** контроль прохождения, моральная поддержка, осмотр территории на помехи, вызов помощи
- **Строгий запрет:** покидать стартовый этаж, если на трассе есть гости

## Снаряжение
- Каска, перчатки, страховочная система (обвязка)
- Два синих уса: малый карабин (доп. страховка) + большой карабин (основная непрерывная страховка)
- Красный ус: блок-ролик для троллея (с оранжевой защёлкой), крепится на оранжевую петлю
- **Любые потёртости или микротрещины (даже на каске или карабине) — немедленная отбраковка**

