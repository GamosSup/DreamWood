## Паспорт аттракциона
- Вместимость: **16 человек** (по 2 в ряду), 16 VR-шлемов
- Высота пика 9,3 м, скорость 12 м/с
- Время проката: **85 секунд**, маршрут — 2 круга

## Погода
- Работаем при температуре **от +5°C** и ветре **до 15 м/с**
- Дождь, снег, град, гроза — **стоп**, ставим табличку

## Кого пускаем
- Рост **строго от 95 см** (измеряем ростомером)
- 95–125 см (примерно 3–6 лет): только со взрослым на соседнем месте
- Выше 125 см: едут сами
- Нельзя: ниже 95 см, беременные, нетрезвые, животные; с длинными шарфами (спрятать под куртку), острыми предметами, пиротехникой

## Документы и чек-лист
- Журнал администратора: отметка механика о тестовом прокате, после неё **ты сам делаешь 1 тестовый круг**
- Журнал передачи смен: время, ФИО, подпись (ушёл на обед — обязательно запиши)
- Журнал VR-наборов: принял 16 шлемов — сдал 16 шлемов
- Чек-лист: аптечка на месте, огнетушитель исправен, диэлектрический коврик под ногами

## Алгоритм запуска
- **Встреча:** «Бодрое утро, искатели приключений! Проходите по двое на правую платформу». Зазыв: «Вы готовы оказаться в сердце гор?»
- **Посадка:** личные вещи оставить на столе; поручень опустить, но без сдавливания. **Критично: турникеты входа обязательно закрыть с пульта**, чтобы очередь не вышла на перрон
- **VR-шлемы:** два ремня (затылок и челюсть) надеваешь **сам**, гости шлемы не трогают. Колёсико резкости сверху — для гостей без очков. Спроси: «Картинка чёткая? Звук есть?» и предупреди: «Пожалуйста, не снимайте шлемы сами, я помогу вам после прибытия!»
- **Двойная проверка:** каждый закрытый поручень дёргаем вверх **дважды**, на пустых местах поручни опускаем. Зелёная лампа в ногах — страховка заблокирована; красная — дожми поручень до лёгкого щелчка. Потом зелёная кнопка на стене платформы и в операторскую
- **Пульт:** стоять строго на диэлектрическом коврике (сойдёшь — аттракцион экстренно встанет). Старт — две зелёные кнопки одновременно
- **Красная кнопка (аварийный стоп):** мгновенная остановка, состав замрёт на горе, гостей придётся эвакуировать пешком. Только при реальной угрозе (паника гостя, неисправность)
- **Чёрная кнопка (обычный стоп):** состав плавно завершит круг и встанет на станции. Чаще нужна именно она

