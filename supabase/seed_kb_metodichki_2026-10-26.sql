- Каналы: **10 — охрана, 4 — врач, 1 — операторы**
- Зажать кнопку сбоку → «Джип Райд вызывает супервайзера» → дождаться «На связи» → отпустить, снова зажать и сообщить суть
- Рация всегда включена и всегда на поясе. Нет ответа — жди беды от начальства

## Инвентарь
- Аптечка + 10 стаканчиков для воды
- Ростомер с метками **95 и 125 см**
- 3 огнетушителя
- Диэлектрический коврик (строго под джипом) и таблички закрытия

## Опасности
- Скользкий пол при посадке и высадке: предупреждай смотреть под ноги
- Паника от VR: остановить, помочь снять шлем
- Беспечность: попытки встать или отстегнуться
- Ухудшение погоды: связь с Альфой

## Журналы и пересменка
- Журнал допуска: утренняя проверка инженерами и супервайзером, твоя подпись о приёме аттракциона
- Журнал шлемов: сколько VR-наборов принял, сколько сдал
- Журнал пересменки: время и передача смены
- **Золотое правило:** на обед или в туалет только после прихода замены (другой Хранитель, Альфа или Супервайзер)

